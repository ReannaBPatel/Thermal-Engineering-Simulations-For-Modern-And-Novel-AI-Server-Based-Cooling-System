def get_exergy_change(conn_in, conn_out):
  m = conn_in.m.val
  h_in, h_out = conn_in.h.val/1000.0, conn_out.h.val/1000.0 #converting to kJ/kg rather than J/kg
  s_in, s_out = conn_in.s.val/1000.0, conn_out.s.val/1000.0

  return m * ((h_in - h_out) - T0_K * (s_in - s_out))

