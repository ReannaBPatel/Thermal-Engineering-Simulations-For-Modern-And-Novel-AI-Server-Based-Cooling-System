import numpy as np
import matplotlib.pyplot as plt

# Wall materials: k (W/mK), rho (kg/m3), cp (J/kgK)
MATERIALS = {
    "copper":    dict(k=395.0, rho=8960.0, cp=385.0),
    "teg":       dict(k=1.5,   rho=7740.0, cp=154.0),   # bismuth telluride thermoelectric layer
    "steel_304": dict(k=16.2,  rho=8000.0, cp=500.0),
}

def solve_1d_thermosyphon_loop(T_evap, T_sink, Q_input, area, h_hot, h_cold, L_cp=0.002, L_hx=0.003,
                               mat_cp="copper", mat_hx="teg", Nx=26, total_steps=600, dt=0.1, zoom_time=3.0):
    """
    Solves 1D heat diffusion across a two-layer wall using live system parameters.
      Layer 1 (0 to L_cp)        : cold plate (mat_cp)
      Layer 2 (L_cp to L_total)  : HX layer   (mat_hx)
      Left face  (x = 0) : heated by the loop-one liquid R134a through a liquid film (h_hot)
      Right face (x = L) : cooled by the loop-two liquid R134a through a liquid film (h_cold)
    total_steps * dt sets how long to simulate; if dt is too large to be stable,
    a smaller safe step is used automatically and total_steps snapshots are still saved.
    """
    L_total = L_cp + L_hx  #thickness (meters)
    x = np.linspace(0, L_total, Nx)
    dx = x[1] - x[0]

    #Material of each segment between neighbouring nodes
    x_mid = 0.5 * (x[:-1] + x[1:])
    in_cp = x_mid < L_cp
    m1, m2 = MATERIALS[mat_cp], MATERIALS[mat_hx]
    k_seg = np.where(in_cp, m1["k"], m2["k"])
    C_seg = np.where(in_cp, m1["rho"] * m1["cp"], m2["rho"] * m2["cp"])

    #Each node owns half of each neighbouring segment
    cap = np.zeros(Nx)                  #heat capacity per m^2 (J/m²K)
    cap[:-1] += C_seg * dx / 2
    cap[1:] += C_seg * dx / 2
    G = k_seg / dx                      #conductance between neighbouring nodes (W/m²K) (del^2 of heat differential equation)
    G_node = np.zeros(Nx)
    G_node[:-1] += G
    G_node[1:] += G
    G_node[0] += h_hot
    G_node[-1] += h_cold

    # Stability - explicit scheme blows up if a node's step is too big
    sim_time = total_steps * dt
    dt_safe = 0.8 * np.min(cap / G_node)
    if dt > dt_safe:
        print(f"dt = {dt} s is unstable for this grid; using {dt_safe:.2e} s instead")
        dt = dt_safe
    n_steps = int(np.ceil(sim_time / dt))
    save_every = max(1, n_steps // total_steps)

    # Initialize temperature array (whole wall starts at coolant temperature)
    T = np.ones(Nx) * T_sink
    snapshots = [T.copy()]
    times = [0.0]
    # Fine-grained record of the first zoom_time seconds
    zoom_every = max(1, int(zoom_time / 300 / dt))
    zoom_snapshots = [T.copy()]
    zoom_times = [0.0]

    # Time-stepping numerical integration
    for step in range(1, n_steps + 1):
        flow = G * (T[1:] - T[:-1])     # heat flowing from node i+1 into node i
        net = np.zeros(Nx)
        net[:-1] += flow
        net[1:] -= flow

        # Physical Boundary Conditions - fluid films on both faces
        net[0] += h_hot * (T_evap - T[0])      # R134a loop one
        net[-1] += h_cold * (T_sink - T[-1])   # Coolant loop two
        T = T + dt * net / cap

        # Save snapshot
        if step % save_every == 0 or step == n_steps:
            snapshots.append(T.copy())
            times.append(step * dt)
        if step * dt <= zoom_time and step % zoom_every == 0:
            zoom_snapshots.append(T.copy())
            zoom_times.append(step * dt)

    T_matrix = np.array(snapshots)
    T_zoom = np.array(zoom_snapshots)
    t_zoom = np.array(zoom_times)

    # Exact steady state - heat flux through film + layers + film in series
    R_seg = dx / k_seg
    R_total = 1/h_hot + R_seg.sum() + 1/h_cold
    q_flux = (T_evap - T_sink) / R_total             # W/m²
    T_face_hot = T_evap - q_flux / h_hot
    T_steady = T_face_hot - q_flux * np.concatenate([[0.0], np.cumsum(R_seg)])

    # Heat the wall passes at steady state, to compare with the loop's Q_input
    Q_wall = q_flux * area

    # Spatial coordinates in mm, time coordinates in seconds
    x_coords = x * 1000
    time_coords = np.array(times)

    return x_coords, time_coords, T_matrix, T_steady, Q_wall, t_zoom, T_zoom

